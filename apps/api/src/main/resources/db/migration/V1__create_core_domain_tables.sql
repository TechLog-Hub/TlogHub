CREATE TABLE company (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(100) NOT NULL,
  name_ko VARCHAR(100) NOT NULL,
  name_en VARCHAR(100) NOT NULL,
  status VARCHAR(30) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uk_company_slug UNIQUE (slug)
);

CREATE INDEX idx_company_status_name_ko ON company (status, name_ko);

CREATE TABLE source_blog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL,
  name VARCHAR(150) NOT NULL,
  homepage_url VARCHAR(500) NOT NULL,
  feed_url VARCHAR(500),
  source_type VARCHAR(30) NOT NULL,
  status VARCHAR(30) NOT NULL,
  review_reason TEXT,
  last_collected_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_source_blog_company FOREIGN KEY (company_id) REFERENCES company (id),
  CONSTRAINT uk_source_blog_feed_url UNIQUE (feed_url)
);

CREATE INDEX idx_source_blog_company_id ON source_blog (company_id);
CREATE INDEX idx_source_blog_status ON source_blog (status);

CREATE TABLE job_category (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL,
  label_ko VARCHAR(100) NOT NULL,
  display_order INTEGER NOT NULL,
  active BOOLEAN NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uk_job_category_code UNIQUE (code)
);

CREATE TABLE topic_tag (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(100) NOT NULL,
  label VARCHAR(100) NOT NULL,
  normalized_label VARCHAR(100) NOT NULL,
  active BOOLEAN NOT NULL,
  merged_to_tag_id BIGINT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_topic_tag_merged_to_tag FOREIGN KEY (merged_to_tag_id) REFERENCES topic_tag (id),
  CONSTRAINT uk_topic_tag_slug UNIQUE (slug)
);

CREATE TABLE archived_post (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_blog_id BIGINT NOT NULL,
  company_id BIGINT NOT NULL,
  slug VARCHAR(180) NOT NULL,
  title VARCHAR(500) NOT NULL,
  origin_url VARCHAR(1000) NOT NULL,
  canonical_url VARCHAR(1000) NOT NULL,
  canonical_fingerprint VARCHAR(128) NOT NULL,
  published_at TIMESTAMP WITH TIME ZONE NOT NULL,
  collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
  processing_state VARCHAR(30) NOT NULL,
  visibility_state VARCHAR(30) NOT NULL,
  review_reason TEXT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_archived_post_source_blog FOREIGN KEY (source_blog_id) REFERENCES source_blog (id),
  CONSTRAINT fk_archived_post_company FOREIGN KEY (company_id) REFERENCES company (id),
  CONSTRAINT uk_archived_post_slug UNIQUE (slug),
  CONSTRAINT uk_archived_post_canonical_fingerprint UNIQUE (canonical_fingerprint)
);

CREATE INDEX idx_archived_post_company_published ON archived_post (company_id, published_at);
CREATE INDEX idx_archived_post_source_blog_id ON archived_post (source_blog_id);
CREATE INDEX idx_archived_post_visibility_published ON archived_post (visibility_state, published_at, id);
CREATE INDEX idx_archived_post_processing_state ON archived_post (processing_state);

CREATE TABLE archived_post_job_category (
  archived_post_id BIGINT NOT NULL,
  job_category_id BIGINT NOT NULL,
  CONSTRAINT fk_archived_post_job_category_post FOREIGN KEY (archived_post_id) REFERENCES archived_post (id),
  CONSTRAINT fk_archived_post_job_category_job FOREIGN KEY (job_category_id) REFERENCES job_category (id),
  CONSTRAINT uk_archived_post_job_category UNIQUE (archived_post_id, job_category_id)
);

CREATE INDEX idx_archived_post_job_category_job ON archived_post_job_category (job_category_id);

CREATE TABLE archived_post_topic_tag (
  archived_post_id BIGINT NOT NULL,
  topic_tag_id BIGINT NOT NULL,
  CONSTRAINT fk_archived_post_topic_tag_post FOREIGN KEY (archived_post_id) REFERENCES archived_post (id),
  CONSTRAINT fk_archived_post_topic_tag_tag FOREIGN KEY (topic_tag_id) REFERENCES topic_tag (id),
  CONSTRAINT uk_archived_post_topic_tag UNIQUE (archived_post_id, topic_tag_id)
