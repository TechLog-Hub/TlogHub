CREATE INDEX idx_archived_post_topic_tag_tag ON archived_post_topic_tag (topic_tag_id);

CREATE TABLE post_source_occurrence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  archived_post_id BIGINT NOT NULL,
  source_blog_id BIGINT NOT NULL,
  origin_url VARCHAR(1000) NOT NULL,
  published_at TIMESTAMP WITH TIME ZONE NOT NULL,
  duplicate_type VARCHAR(30) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_post_source_occurrence_post FOREIGN KEY (archived_post_id) REFERENCES archived_post (id),
  CONSTRAINT fk_post_source_occurrence_source FOREIGN KEY (source_blog_id) REFERENCES source_blog (id),
  CONSTRAINT uk_post_source_occurrence_source_url UNIQUE (source_blog_id, origin_url)
);

CREATE INDEX idx_post_source_occurrence_archived_post_id ON post_source_occurrence (archived_post_id);

